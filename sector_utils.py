# KIS 응답의 rprs_mrkt_kor_name 패턴 매칭
def normalize_market(raw_market: str | None) -> str:
    """
    KIS 응답의 시장 구분 텍스트를 표준 라벨로 정규화.
    "KOSPI200", "유가증권" → "KOSPI"
    "KOSDAQ150", "코스닥" → "KOSDAQ"
    그 외 → "기타"
    """
    if not raw_market:
        return "기타"
    txt = raw_market.strip().upper()
    if "KOSPI" in txt or "코스피" in raw_market or "유가증권" in raw_market:
        return "KOSPI"
    if "KOSDAQ" in txt or "코스닥" in raw_market:
        return "KOSDAQ"
    return "기타"
