def normalize_sector(s: str | None) -> str | None:
    """
    섹터명 정규화 — 표준 12개 중 하나로 매핑.

    Returns:
        - 입력이 None/빈문자열이면 None
        - SECTOR_ALIASES에 매핑 있으면 표준 카테고리
        - 매핑 없으면 "기타" (rescue)
    """
    if not s:
        return None
    key = s.strip()
    if key in SECTOR_ALIASES:
        return SECTOR_ALIASES[key]
    # 매핑에 없는 신규 표기 — 모두 "기타"로 (사용자에게 보이는 표기는 항상 12개 중 하나 보장)
    return "기타"


def is_canonical_sector(s: str | None) -> bool:
    """정규화된 표준 카테고리 12개에 속하는지 확인."""
    return s in CANONICAL_SECTORS


