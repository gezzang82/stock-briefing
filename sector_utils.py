"""
섹터명 정규화 유틸 — 표시 단계에서 사용 (DB의 raw 값은 보존).

AI가 매번 다른 표기로 sector를 분류해 같은 의미의 섹터가 분산되는 문제 대응:
  '제약 바이오' + '제약/바이오' → '제약/바이오' (1개로 합산)
  'IT/서비스', 'IT/통신장비', 'IT' → 'IT' (3개 통합)

⚠️ DB의 recommendations.sector 컬럼은 절대 수정하지 않음.
   정규화는 표시 단계 (HTML 대시보드 / 카톡 / 통계)에서만 적용.
"""

# 정규화 매핑 — 키는 raw sector명, 값은 표시용 정규화명
SECTOR_ALIASES = {
    # 제약/바이오 계열 통합
    "제약 바이오": "제약/바이오",
    "바이오/제약": "제약/바이오",
    "바이오": "제약/바이오",
    "헬스케어": "제약/바이오",
    "의약품": "제약/바이오",
    # IT 계열 통합 (사용자 요구사항)
    "IT": "IT",
    "IT/서비스": "IT",
    "IT/통신장비": "IT",
    "통신장비": "IT",
    "통신": "IT",
    "소프트웨어": "IT",
    "소프트웨어/IT": "IT",
    "인터넷": "IT",
    # 전자/반도체는 별도 유지 (산업 분류상 다른 카테고리)
    "전자": "전자",
    "반도체": "반도체",
    # AI는 별도 유지 (테마성 섹터)
    "AI": "AI",
}


def normalize_sector(s: str | None) -> str | None:
    """섹터명 정규화 — alias 매핑. 없는 키는 trim만 적용해 그대로 반환."""
    if not s:
        return None
    key = s.strip()
    return SECTOR_ALIASES.get(key, key)
